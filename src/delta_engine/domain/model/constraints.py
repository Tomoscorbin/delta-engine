"""Domain value objects representing key constraints (primary and foreign)."""

from collections.abc import Iterable
from dataclasses import dataclass

from delta_engine.domain.model.identifier import identifier_key
from delta_engine.domain.model.qualified_name import QualifiedName

KeySignature = frozenset[str]


def key_signature(columns: Iterable[str]) -> KeySignature:
    """Return the order-independent, case-insensitive identity of a key's columns."""
    return frozenset(identifier_key(column) for column in columns)


@dataclass(frozen=True, slots=True)
class PrimaryKeyConstraint:
    """
    A primary key constraint declaration.

    Symmetric with :class:`ForeignKeyConstraint`: a table-level key constraint
    over an ordered set of columns.

    Attributes:
        columns: Ordered tuple of column names, preserving their supplied
            spelling. Identity and duplicates are judged by identifier key.
        constraint_name: The constraint name, preserved verbatim. Generated by
            the API layer when a ``DeltaTable`` is lowered to a
            ``DesiredTable`` (``{table}_pk``), and read from the catalog for
            observed constraints.

    """

    columns: tuple[str, ...]
    constraint_name: str

    @property
    def signature(self) -> KeySignature:
        """Content identity, excluding physical name and declaration order."""
        return key_signature(self.columns)

    def __post_init__(self) -> None:
        if not self.columns:
            raise ValueError("columns must not be empty")

        seen: set[str] = set()
        for column in self.columns:
            key = identifier_key(column)
            if key in seen:
                raise ValueError(f"Duplicate primary key column: {column}")
            seen.add(key)

        if not self.constraint_name.strip():
            raise ValueError("constraint_name must not be blank")


@dataclass(frozen=True, slots=True)
class ForeignKeyConstraint:
    """
    A foreign key constraint declaration.

    Attributes:
        local_columns: Tuple of local column names in the constraint,
            preserving spelling and stored sorted by identifier key (pairing
            with ``referenced_columns`` preserved). Column order is not part of
            a foreign key's meaning, mirroring the primary key's set identity,
            so identity, generated names, and rendered DDL are independent of
            declaration order.
        referenced_table: Fully qualified name of the referenced table.
        referenced_columns: Tuple of column names in the referenced table,
            positionally aligned with ``local_columns`` after identity-key sorting.
        constraint_name: The constraint name, preserved verbatim. Generated by
            the API layer when a ``DeltaTable`` is lowered to a ``DesiredTable``
            (``{table}_{local_cols}_fk``), and read from the catalog for observed
            constraints. Excluded from ``signature``, so a desired and an
            observed constraint still match by content even though constraint
            names preserve their spelling — no migration churn for existing
            catalogs.

    """

    local_columns: tuple[str, ...]
    referenced_table: QualifiedName
    referenced_columns: tuple[str, ...]
    constraint_name: str

    def __post_init__(self) -> None:
        if not self.local_columns:
            raise ValueError("local_columns must not be empty")

        if not self.referenced_columns:
            raise ValueError("referenced_columns must not be empty")

        if len(self.local_columns) != len(self.referenced_columns):
            raise ValueError(
                "local_columns and referenced_columns must have the same number of entries;"
                f" got {len(self.local_columns)} local and"
                f" {len(self.referenced_columns)} referenced"
            )

        # Pairs are stored sorted by the local column's identity key. Column
        # order is not part of a foreign key's meaning (mirroring the primary
        # key's set identity), so one canonical order makes identity,
        # generated names, and rendered DDL independent of declaration order
        # and case — while both original spellings are retained.
        pairs = sorted(
            zip(self.local_columns, self.referenced_columns, strict=True),
            key=lambda pair: identifier_key(pair[0]),
        )
        object.__setattr__(self, "local_columns", tuple(pair[0] for pair in pairs))
        object.__setattr__(self, "referenced_columns", tuple(pair[1] for pair in pairs))

        seen_local: set[str] = set()
        for column in self.local_columns:
            key = identifier_key(column)
            if key in seen_local:
                raise ValueError(f"Duplicate foreign key local column: {column}")
            seen_local.add(key)

        seen_referenced: set[str] = set()
        for column in self.referenced_columns:
            key = identifier_key(column)
            if key in seen_referenced:
                raise ValueError(f"Duplicate foreign key referenced column: {column}")
            seen_referenced.add(key)

        if not self.constraint_name.strip():
            raise ValueError("constraint_name must not be blank")

    @property
    def signature(self) -> tuple[tuple[str, ...], QualifiedName, tuple[str, ...]]:
        """
        Content identity: local columns, referenced table, referenced columns.

        Column entries are identity keys, so a desired constraint and a
        catalog-observed one compare equal across display casing. Excludes
        ``constraint_name`` so generated and catalog names still match by
        content.
        """
        return (
            tuple(identifier_key(column) for column in self.local_columns),
            self.referenced_table,
            tuple(identifier_key(column) for column in self.referenced_columns),
        )

    @property
    def referenced_key_signature(self) -> KeySignature:
        """Identity of the primary key targeted by this foreign key."""
        return key_signature(self.referenced_columns)


@dataclass(frozen=True, slots=True)
class ForeignKeyReference:
    """
    A foreign key on some table that references *this* table's key.

    The inbound counterpart of :class:`ForeignKeyConstraint`: it identifies
    the referencing constraint and its owner without carrying column detail —
    enough for validation to name what blocks a primary-key change.

    Attributes:
        constraint_name: The referencing constraint's name, as read from the
            catalog.
        referencing_table: Fully qualified name of the table that owns the
            referencing constraint.

    """

    constraint_name: str
    referencing_table: QualifiedName

    def __post_init__(self) -> None:
        if not self.constraint_name.strip():
            raise ValueError("constraint_name must not be blank")
