"""Schema declaration implementation for Delta tables and foreign keys."""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from typing import Final

from delta_engine.application.properties import (
    COLUMN_MAPPING_MODE_KEY,
    DELTA_PROPERTY_REGISTRY,
    Property,
)
from delta_engine.domain.model import (
    ALL_ASPECTS,
    Column,
    DesiredTable,
    ForeignKeyConstraint,
    PrimaryKeyConstraint,
    QualifiedName,
    TableAspect,
)


class _SelfReference:
    """Sentinel marking a foreign key that references its own table."""

    __slots__ = ()

    def __repr__(self) -> str:
        return "Self"


Self: Final = _SelfReference()

METADATA_ASPECTS: Final[frozenset[TableAspect]] = frozenset(
    {
        TableAspect.TABLE_COMMENT,
        TableAspect.COLUMN_COMMENTS,
        TableAspect.COLUMN_TAGS,
        TableAspect.TABLE_TAGS,
        TableAspect.PRIMARY_KEY,
        TableAspect.FOREIGN_KEYS,
    }
)

# Delta permits these characters in column names only under column mapping.
_CHARACTERS_REQUIRING_COLUMN_MAPPING: Final[frozenset[str]] = frozenset(" ,;{}()\n\t=")

# Column names change data feed reserves for its own output columns.
_CDF_RESERVED_COLUMN_NAMES: Final[frozenset[str]] = frozenset(
    {"_change_type", "_commit_version", "_commit_timestamp"}
)


@dataclass(frozen=True, slots=True)
class ForeignKey:
    """
    Public declaration of a foreign key relationship.

    Names the local columns and the table they reference. The referenced
    columns are always the referenced table's primary key, aligned positionally
    with ``local_columns`` in the referenced table's primary-key declaration
    order. The physical constraint name is generated by the engine and is not
    part of this declaration.

    ``references`` is another :class:`DeltaTable`, or the :data:`Self` sentinel
    for a self-referential key. See the architecture explanation doc for why the
    reference is an object rather than a name.
    """

    local_columns: tuple[str, ...]
    references: DeltaTable | _SelfReference

    def _to_constraint(
        self, owner_name: QualifiedName, owner_primary_key: tuple[str, ...]
    ) -> ForeignKeyConstraint:
        """
        Lower this declaration into a domain constraint.

        Resolves ``references`` to a concrete table and infers the referenced
        columns from that table's primary key. ``owner_name`` and
        ``owner_primary_key`` describe the enclosing table, used when
        ``references`` is :data:`Self`.
        """
        match self.references:
            case _SelfReference():
                referenced_table, referenced_columns = owner_name, owner_primary_key
            case DeltaTable() as target:
                desired = target.to_desired_table()
                referenced_table = desired.qualified_name
                referenced_columns = desired.primary_key_columns
            case _:
                raise TypeError(
                    f"foreign key references must be a DeltaTable or Self; got {self.references!r}"
                )

        if not referenced_columns:
            raise ValueError(
                f"cannot infer referenced columns: {referenced_table} declares no primary key"
            )
        if len(self.local_columns) != len(referenced_columns):
            raise ValueError(
                "foreign key local column count must match the referenced primary key;"
                f" {owner_name} declares {len(self.local_columns)} local column(s)"
                f" but {referenced_table}'s primary key has {len(referenced_columns)}"
            )
        return ForeignKeyConstraint.generate(
            owner_table_name=owner_name.name,
            local_columns=tuple(self.local_columns),
            referenced_table=referenced_table,
            referenced_columns=tuple(referenced_columns),
        )


class DeltaTable:
    """
    Defines a Delta table schema.

    Note on dropping columns: Delta only permits ``ALTER TABLE ... DROP COLUMN``
    when ``delta.columnMapping.mode`` is ``name``. Declare it in ``properties``
    on any table whose columns may be dropped; a sync that drops a column
    without it fails at validation with a message naming the property.
    """

    def __init__(
        self,
        catalog: str,
        schema: str,
        name: str,
        columns: Iterable[Column],
        comment: str = "",
        properties: Mapping[str, str | None] | None = None,
        tags: dict[str, str] | None = None,
        partitioned_by: Iterable[str] = (),
        foreign_keys: Iterable[ForeignKey] | None = None,
        metadata_only: bool = False,
    ) -> None:
        """
        Initialise a DeltaTable definition.

        Args:
            catalog: Unity Catalog catalog name.
            schema: Schema (database) name within the catalog.
            name: Table name.
            columns: Ordered column declarations.
            comment: Table-level comment.
            properties: Delta/Spark table properties to manage.
            tags: Key/value tags to apply to the table.
            partitioned_by: Column names to partition by.
            foreign_keys: Foreign key relationships declared on this table.
            metadata_only: When ``True``, restricts the sync to catalog metadata:
                comments, tags, and key constraints. The full table is still
                declared — columns, properties, partitioning — but only
                metadata is deployed; the rest is never compared or changed,
                except that the live schema must match the declared columns
                exactly (structural drift fails validation).

        """
        user_properties = dict(properties or {})

        # Fast-fail on property keys this engine does not manage (e.g. typos).
        # None-valued assertions are validated too: asserting absence of an
        # unmanaged key is as meaningless as declaring it.
        if user_properties:
            unmanaged = [k for k in user_properties if k not in DELTA_PROPERTY_REGISTRY]
            if unmanaged:
                raise ValueError(
                    f"Properties not managed by this engine: {', '.join(sorted(unmanaged))}"
                )

        # Fast-fail on malformed values. Declared None asserts absence, not a
        # value, so it is exempt from this check.
        for key, declared_value in user_properties.items():
            if declared_value is None:
                continue
            definition = DELTA_PROPERTY_REGISTRY[key]
            if not definition.is_valid_value(declared_value):
                raise ValueError(
                    f"Invalid value for {key}: {declared_value!r}."
                    f" Expected {definition.value_description}."
                )

        columns = tuple(columns)

        if not metadata_only and user_properties.get(COLUMN_MAPPING_MODE_KEY) != "name":
            offending = [
                column.name
                for column in columns
                if set(column.name) & _CHARACTERS_REQUIRING_COLUMN_MAPPING
            ]
            if offending:
                raise ValueError(
                    f"Column names {offending} contain characters Delta only"
                    " permits with column mapping. Declare"
                    f" properties={{'{COLUMN_MAPPING_MODE_KEY}': 'name'}}"
                    " or rename the columns."
                )

        if not metadata_only and user_properties.get(Property.CHANGE_DATA_FEED) == "true":
            reserved = [
                column.name for column in columns if column.name in _CDF_RESERVED_COLUMN_NAMES
            ]
            if reserved:
                raise ValueError(
                    f"Column names {reserved} are reserved by change data feed."
                    " Rename them or do not enable"
                    f" {Property.CHANGE_DATA_FEED}."
                )

        primary_key_columns = tuple(column.name for column in columns if column.primary_key)
        primary_key = (
            PrimaryKeyConstraint.generate(table_name=name, columns=primary_key_columns)
            if primary_key_columns
            else None
        )

        qualified_name = QualifiedName(catalog, schema, name)
        lowered_foreign_keys = tuple(
            declaration._to_constraint(qualified_name, primary_key_columns)
            for declaration in (foreign_keys or ())
        )

        # Building DesiredTable here enforces all domain invariants (non-empty
        # columns, unique names, partition columns must exist, FK local columns
        # must exist) at construction time rather than deferring them to
        # to_desired_table().
        self._desired_table = DesiredTable(
            qualified_name=qualified_name,
            columns=columns,
            comment=comment,
            properties=user_properties,
            tags=dict(tags or {}),
            partitioned_by=tuple(partitioned_by),
            primary_key=primary_key,
            foreign_keys=lowered_foreign_keys,
            managed_aspects=METADATA_ASPECTS if metadata_only else ALL_ASPECTS,
        )

    @property
    def primary_key(self) -> tuple[str, ...]:
        """Column names declared as the primary key, in declaration order."""
        return self._desired_table.primary_key_columns

    @property
    def foreign_keys(self) -> tuple[ForeignKeyConstraint, ...]:
        """Foreign key constraints declared on this table."""
        return self._desired_table.foreign_keys

    def to_desired_table(self) -> DesiredTable:
        """Return the domain :class:`DesiredTable` for this table definition."""
        return self._desired_table
